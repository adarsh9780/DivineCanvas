const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const ts = require(root + '/node_modules/typescript');
const source = fs.readFileSync(root + '/src/lookupGesture.ts', 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const api = {}; new Function('exports', compiled)(api);
const tap = {time:1000,x:100,y:100,passageId:'gita:1'};
assert.equal(api.isDoubleTap(tap, {...tap,time:1300,x:108}),true);
assert.equal(api.isDoubleTap(tap, {...tap,time:1400}),false);
assert.equal(api.isDoubleTap(tap, {...tap,time:1100,x:140}),false);
assert.equal(api.isDoubleTap(tap, {...tap,time:1100,passageId:'gita:2'}),false);
assert.equal(api.isDoubleTap(null, tap),false);
assert.equal(api.selectedLookupWord('"wisdom", compassion',0,8),'wisdom');
assert.equal(api.selectedLookupWord('कर्म योग',0,4),'कर्म');
assert.equal(api.selectedLookupWord('two words',0,9),null);
assert.equal(api.selectedLookupWord('word',2,2),null);
console.log('PASS: double taps require matching passages, timing, and proximity; selected words are validated.');
const mixed = 'कर्म योग, wisdom’s path!\n🕉️ शान्ति';
const parts = api.segmentPassage(mixed);
assert.equal(parts.map(part => part.text).join(''),mixed);
assert.deepEqual(parts.filter(part=>part.word).map(part=>part.text),['कर्म','योग','wisdom’s','path','शान्ति']);
for (const part of parts) assert.equal(mixed.slice(part.start,part.end),part.text);
assert.deepEqual(api.selectionRange(5,8,0,4),{start:0,end:8});
assert.deepEqual(api.selectionRange(0,4,9,17),{start:0,end:17});
console.log('PASS: selection preserves Unicode text, punctuation and whitespace and extends in either direction.');
