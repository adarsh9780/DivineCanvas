const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {DatabaseSync}=require('node:sqlite');
const ts=require('typescript');
const source=fs.readFileSync('src/readerWalkthrough.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const api={};new Function('exports',js)(api);
const folder=fs.mkdtempSync(path.join(os.tmpdir(),'walkthrough-'));
const file=path.join(folder,'settings.db');
let db=new DatabaseSync(file);
db.exec('CREATE TABLE settings (key TEXT PRIMARY KEY NOT NULL, value TEXT NOT NULL)');
const read=(key=api.READER_WALKTHROUGH_KEY)=>api.readerWalkthroughSeen(db.prepare('SELECT value FROM settings WHERE key=?').get(key)?.value);
const save=(value,key=api.READER_WALKTHROUGH_KEY)=>db.prepare('INSERT OR REPLACE INTO settings (key,value) VALUES (?,?)').run(key,value);
assert.equal(read(),false);
save('true');db.close();db=new DatabaseSync(file);assert.equal(read(),true);
save('false');db.close();db=new DatabaseSync(file);assert.equal(read(),false);
save('true');db.close();db=new DatabaseSync(file);assert.equal(read(),true);
assert.equal(read(api.PRASHNAVALI_WALKTHROUGH_KEY),false);
save('true',api.PRASHNAVALI_WALKTHROUGH_KEY);db.close();db=new DatabaseSync(file);
assert.equal(read(),true);assert.equal(read(api.PRASHNAVALI_WALKTHROUGH_KEY),true);
save('false',api.PRASHNAVALI_WALKTHROUGH_KEY);db.close();db=new DatabaseSync(file);
assert.equal(read(),true);assert.equal(read(api.PRASHNAVALI_WALKTHROUGH_KEY),false);
save('true',api.PRASHNAVALI_WALKTHROUGH_KEY);save('false');db.close();db=new DatabaseSync(file);
assert.equal(read(),false);assert.equal(read(api.PRASHNAVALI_WALKTHROUGH_KEY),true);
db.close();fs.rmSync(folder,{recursive:true});
console.log('PASS: both walkthroughs persist independently across restarts and resets.');
