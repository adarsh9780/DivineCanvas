const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const ts = require(root + '/node_modules/typescript');
const source = fs.readFileSync(root + '/src/musicQueue.ts', 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const music = {}; new Function('exports', compiled)(music);
assert.deepEqual(music.normalizeMusicOrder(['b','bad','b','a'], ['a','b','c']), ['b','a','c']);
assert.deepEqual(music.normalizeMusicOrder(null, ['a','b']), ['a','b']);
assert.deepEqual(music.moveMusic(['a','b','c'],'a','c'), ['c','b','a']);
assert.deepEqual(music.moveAvailableMusic(['a','x','b','c'],['a','b','c'],'a','c'), ['b','x','c','a']);
assert.deepEqual(music.moveAvailableMusic(['a','x','b','c'],['a','b','c'],'c','a'), ['c','x','a','b']);
const layouts={a:{y:100,height:80},b:{y:180,height:100},c:{y:280,height:120}};
assert.equal(music.musicDropTarget(['a','b','c'],layouts,'a',0),'a');
assert.equal(music.musicDropTarget(['a','b','c'],layouts,'a',100),'b');
assert.equal(music.musicDropTarget(['a','b','c'],layouts,'a',240),'c');
assert.equal(music.musicDropTarget(['a','b','c'],layouts,'c',-220),'a');
assert.equal(music.nextMusic(['a','b','c'],'b',false), 'c');
assert.equal(music.nextMusic(['a','b','c'],'c',false), 'a');
assert.equal(music.nextMusic(['a','b','c'],'missing',false), 'a');
assert.equal(music.nextMusic(['a','b','c'],'b',true,0), 'a');
assert.equal(music.nextMusic(['a','b','c'],'b',true,0.99), 'c');
assert.equal(music.nextMusic(['a'],'a',true), 'a');
assert.equal(music.nextMusic([],'a',true), undefined);
console.log('PASS: saved music order, reordering, sequential looping and shuffle.');
