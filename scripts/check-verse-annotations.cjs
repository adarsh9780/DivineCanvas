const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {DatabaseSync} = require('node:sqlite');
const ts = require('typescript');
const source = fs.readFileSync('src/verseAnnotations.ts','utf8');
const api = {};
new Function('exports',ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(api);
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'verse-annotations-'));
const file=path.join(dir,'settings.db');
let db=new DatabaseSync(file);
db.exec("CREATE TABLE saves (id TEXT PRIMARY KEY NOT NULL, note TEXT NOT NULL DEFAULT '');");
db.prepare('INSERT INTO saves VALUES (?,?)').run('gita:1:1','An existing note');
db.prepare('INSERT INTO saves VALUES (?,?)').run('gita:1:2','');
db.exec(api.MIGRATE_NOTES_SQL);
assert.deepEqual(db.prepare('SELECT id,note FROM verse_notes').all().map(row=>({...row})),[{id:'gita:1:1',note:'An existing note'}]);
assert.equal(db.prepare('SELECT count(*) AS n FROM saves').get().n,2);
assert.equal(db.prepare('SELECT note FROM saves WHERE id=?').get('gita:1:1').note,'');
db.prepare('DELETE FROM saves WHERE id=?').run('gita:1:1');
db.prepare('INSERT INTO verse_notes VALUES (?,?)').run('gita:1:3','A note without a like');
db.close(); db=new DatabaseSync(file); db.exec(api.MIGRATE_NOTES_SQL);
assert.equal(db.prepare('SELECT note FROM verse_notes WHERE id=?').get('gita:1:1').note,'An existing note');
assert.equal(db.prepare('SELECT note FROM verse_notes WHERE id=?').get('gita:1:3').note,'A note without a like');
assert.equal(db.prepare('SELECT count(*) AS n FROM saves WHERE id=?').get('gita:1:3').n,0);
db.prepare('DELETE FROM verse_notes WHERE id=?').run('gita:1:1');
db.exec(api.MIGRATE_NOTES_SQL);
assert.equal(db.prepare('SELECT count(*) AS n FROM verse_notes WHERE id=?').get('gita:1:1').n,0);
assert.equal(db.prepare('SELECT count(*) AS n FROM saves WHERE id=?').get('gita:1:2').n,1);
db.close();fs.rmSync(dir,{recursive:true});
console.log('PASS: legacy notes migrate safely; likes and notes persist and delete independently.');
